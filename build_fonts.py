"""Embed the Fira font files in assets/fonts.css as data URLs.

Chrome blocks font files on file:// pages (CORS), so the dashboard ships its fonts inline, the same way
assets/maternity-access.js ships the drive-time rasters. Run after changing anything in assets/fonts/:

    python3 build_fonts.py
"""
import base64
from pathlib import Path

ROOT = Path(__file__).parent
FONTS = ROOT / "assets" / "fonts"
OUT = ROOT / "assets" / "fonts.css"

FACES = [
    ("Fira Sans", "normal", 400, "fira-sans-latin-400-normal.woff2"),
    ("Fira Sans", "italic", 400, "fira-sans-latin-400-italic.woff2"),
    ("Fira Sans", "normal", 500, "fira-sans-latin-500-normal.woff2"),
    ("Fira Sans", "normal", 600, "fira-sans-latin-600-normal.woff2"),
    ("Fira Sans Condensed", "normal", 500, "fira-sans-condensed-latin-500-normal.woff2"),
    ("Fira Sans Condensed", "normal", 600, "fira-sans-condensed-latin-600-normal.woff2"),
    ("Fira Mono", "normal", 400, "fira-mono-latin-400-normal.woff2"),
]


def main():
    rules = [
        "/* Generated by build_fonts.py from assets/fonts/*.woff2 (SIL Open Font License, see FiraSans-OFL.txt). */"
    ]
    for family, style, weight, name in FACES:
        data = base64.b64encode((FONTS / name).read_bytes()).decode("ascii")
        rules.append(
            f'@font-face {{ font-family: "{family}"; font-style: {style}; font-weight: {weight}; font-display: swap; '
            f'src: url(data:font/woff2;base64,{data}) format("woff2"); }}'
        )
    OUT.write_text("\n".join(rules) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1024:.0f} KB, {len(FACES)} faces)")


if __name__ == "__main__":
    main()
