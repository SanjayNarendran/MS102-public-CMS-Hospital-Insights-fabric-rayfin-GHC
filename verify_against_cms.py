#!/usr/bin/env python3
"""Independently re-derive Fig 1 (national pooled SIR by infection and report year) from CMS's
own archived Care Compare files and compare it with assets/data.js.

For each report year the script streams only the HAI hospital CSV out of the matching CMS
archive snapshot (HTTP range requests, ~15 MB read per snapshot), sums observed and predicted
cases per infection, and checks totals and hospital counts against the dashboard data.
Results are written to assets/verification.js, which the dashboard's Explain panel shows.

    python3 verify_against_cms.py
"""
import csv
import datetime as dt
import io
import json
import os
import sys
import zipfile

from cms_archive import ARCHIVE_PAGE, BASE, HttpRangeFile
from cms_archive import SNAPSHOTS as _SNAPSHOTS

ROOT = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(ROOT, "assets", "data.js")
OUT = os.path.join(ROOT, "assets", "verification.js")
# Report year -> CMS archive snapshot whose HAI file covers the same period (shared with build_core_tables.py)
SNAPSHOTS = {year: f"hospitals_{date}.zip" for year, date in _SNAPSHOTS["hai"].items()}
HAI_FILES = ("Healthcare_Associated_Infections-Hospital.csv", "77hc-ibv8.csv")


def load_data():
    s = open(DATA, encoding="utf-8").read()
    return json.loads(s[s.index("{"): s.rstrip().rindex(";")])


def cms_totals(snapshot):
    archive = zipfile.ZipFile(io.BufferedReader(HttpRangeFile(BASE + snapshot), buffer_size=1 << 20))
    member = next(n for n in archive.namelist() if n.endswith(HAI_FILES))
    totals, periods = {}, set()
    with archive.open(member) as fh:
        for row in csv.DictReader(io.TextIOWrapper(fh, encoding="utf-8-sig")):
            periods.add((row["Start Date"], row["End Date"]))
            try:
                value = float(row["Score"])
            except ValueError:  # "Not Available" / "N/A"
                continue
            t = totals.setdefault(row["Measure ID"], [0, 0.0])
            t[0] += 1
            t[1] += value
    return member, sorted(periods), totals


def main():
    data = load_data()
    keys = [i["key"] for i in data["infections"]]
    trend = {t["year"]: t for t in data["haiTrend"]}
    years = []
    all_match = True
    for year in sorted(trend):
        snapshot = SNAPSHOTS.get(year)
        if not snapshot:
            years.append({"year": year, "status": "not-mapped"})
            all_match = False
            continue
        print(f"Report year {year}: reading {snapshot} …", flush=True)
        member, periods, totals = cms_totals(snapshot)
        infections = {}
        for i, k in enumerate(keys, 1):
            obs_n, obs = totals[f"HAI_{i}_NUMERATOR"]
            _, pred = totals[f"HAI_{i}_ELIGCASES"]
            sir_n = totals.get(f"HAI_{i}_SIR", [0])[0]
            m = trend[year][k]
            match = round(obs) == m["obs"] and abs(pred - m["pred"]) < 0.0005 and sir_n == m["n"] and obs_n == m.get("reporting")
            all_match &= match
            infections[k] = {"cmsObserved": round(obs), "cmsPredicted": round(pred, 3), "cmsSir": round(obs / pred, 6),
                             "cmsHospitalsReporting": obs_n, "cmsHospitalsWithSir": sir_n, "match": match}
        years.append({"year": year, "snapshot": snapshot, "url": BASE + snapshot, "file": member.rsplit("/", 1)[-1],
                      "periods": periods, "status": "match" if all(v["match"] for v in infections.values()) else "diff",
                      "infections": infections})
        print(f"   {years[-1]['status']}  period {periods}")
    result = {"checkedAt": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "dataExtracted": data["meta"]["extracted"],
              "archivePage": ARCHIVE_PAGE, "allMatch": all_match, "years": years}
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("// Generated by verify_against_cms.py — independent check of Fig 1 against CMS archived files.\n")
        fh.write("window.CMS_VERIFICATION = " + json.dumps(result, separators=(",", ":")) + ";\n")
    print(f"Wrote {OUT}: {'ALL MATCH' if all_match else 'DIFFERENCES FOUND'}")
    sys.exit(0 if all_match else 1)


if __name__ == "__main__":
    main()
